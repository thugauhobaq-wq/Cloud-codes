async def seed(storage: Storage) -> bool:
    """Наполнить пустую базу. `False` — магниты уже есть, ничего не трогали."""
    if await storage.list_magnets(only_active=False):
        return False

    for code, title, body, followup in DEMO_MAGNETS:
        await storage.add_magnet(code, title, kind=KIND_TEXT, body=body, followup=followup)
    return True
