_WORD_RE = re.compile(r"[а-яёa-z]+", re.IGNORECASE)
_MIN_STEM = 3


@dataclass
class SentimentResult:
    label: str          # positive | neutral | negative
    score: float        # -1..1
    confidence: float   # 0..1
    hits: int           # сколько оценочных слов нашли
    aspects: dict[str, float]
    keywords: list[str]


def tokenize(text: str) -> list[str]:
    return _WORD_RE.findall((text or "").lower())


# Глагольные приставки: «нахамил» → «хамил», «переплатил» → «платил».
# «не»/«ни» здесь сознательно нет — это отрицания, они обрабатываются отдельно.
PREFIXES = ("на", "по", "за", "пере", "при", "про", "раз", "разо",
            "изо", "из", "ис", "обо", "об", "подо", "под", "во", "до", "у", "о")


def _lookup(token: str, lexicon: dict[str, float]) -> float:
    """Ищет самое длинное совпадение основы слова с началом токена."""
    for size in range(len(token), _MIN_STEM - 1, -1):
        weight = lexicon.get(token[:size])
        if weight is not None:
            return weight

    # Слово с приставкой: отсекаем её и пробуем ещё раз, но уже с меньшим весом.
    for prefix in PREFIXES:
        if not token.startswith(prefix) or len(token) - len(prefix) < _MIN_STEM:
            continue
        stem = token[len(prefix):]
        for size in range(len(stem), _MIN_STEM - 1, -1):
            weight = lexicon.get(stem[:size])
            if weight is not None:
                return weight * 0.9
    return 0.0


def _phrase_bonus(text: str) -> float:
    """Устойчивые выражения, которые пословный разбор ловит плохо."""
    bonus = 0.0
    # Ищем по границам слов: иначе «мне понравилось» содержит «не понравилось».
    low = " " + re.sub(r"\s+", " ", re.sub(r"[^а-яёa-z]+", " ", text.lower())).strip() + " "
    for phrase, weight in (
        ("не рекомендую", -2.0), ("не советую", -2.0), ("больше не приду", -2.0),
        ("никогда больше", -2.0), ("зря потратил", -1.8), ("деньги на ветер", -2.0),
        ("обходите стороной", -2.2), ("развод на деньги", -2.2),
        ("оставляет желать лучшего", -1.5), ("ни рыба ни мясо", -0.8),
        ("всем рекомендую", 2.0), ("однозначно рекомендую", 2.2),
        ("буду обращаться", 1.5), ("вернусь ещё", 1.5), ("вернусь еще", 1.5),
        ("на высоте", 1.8), ("выше всяких похвал", 2.2),
        ("без нареканий", 1.6), ("всё понравилось", 1.8), ("все понравилось", 1.8),
        ("не понравилось", -1.6), ("не оправдал", -1.6),
    ):
        if f" {phrase} " in low:
            bonus += weight
    return bonus


def analyze(text: str, rating: float | None = None) -> SentimentResult:
    """Считает тональность текста, при наличии — с учётом оценки в звёздах."""
    text = text or ""
    tokens = tokenize(text)
    total = 0.0
    hits = 0
    keywords: list[tuple[float, str]] = []
    values = [0.0] * len(tokens)  # вклад каждого слова — нужен для аспектов

    # Вес фрагмента после «но» выше: «еда вкусная, но обслуживание ужасное».
    clause_marks = _clause_weights(tokens)

    for index, token in enumerate(tokens):
        weight = _lookup(token, POSITIVE) or _lookup(token, NEGATIVE)
        if not weight:
            continue

        multiplier = 1.0
        negated = False
        for back in range(1, 4):
            prev_index = index - back
            if prev_index < 0:
                break
            prev = tokens[prev_index]
            if prev in NEGATORS:
                negated = True
                continue
            multiplier *= INTENSIFIERS.get(prev, DIMINISHERS.get(prev, 1.0))

        value = weight * multiplier * clause_marks[index]
        if negated:
            # «не плохо» — слабый плюс, «не понравилось» — минус.
            value = -value * 0.75

        total += value
        hits += 1
        values[index] = value
        keywords.append((value, token))

    aspect_scores = _aspect_scores(tokens, values)
    total += _phrase_bonus(text)

    for char in text:
        if char in EMOJI_POSITIVE:
            total += 0.8
            hits += 1
        elif char in EMOJI_NEGATIVE:
            total -= 0.9
            hits += 1

    if text.count("!") >= 2:
        total *= 1.15

    text_score = total / (abs(total) + 3.0)  # мягкое сжатие в диапазон -1..1

    if rating is not None:
        rating_score = (float(rating) - 3.0) / 2.0
        text_weight = min(0.55, 0.14 * hits)
        score = rating_score * (1 - text_weight) + text_score * text_weight
        confidence = 0.6 + min(0.4, 0.05 * hits)
    else:
        score = text_score
        confidence = min(0.95, 0.25 + 0.12 * hits)

    score = max(-1.0, min(1.0, score))
    if score >= 0.15:
        label = "positive"
    elif score <= -0.15:
        label = "negative"
    else:
        label = "neutral"

    aspects = aspect_scores
    keywords.sort(key=lambda item: -abs(item[0]))
    top_keywords = [word for _, word in keywords[:6]]

    return SentimentResult(
        label=label,
        score=round(score, 3),
        confidence=round(confidence, 2),
        hits=hits,
        aspects=aspects,
        keywords=top_keywords,
    )


def _aspect_scores(tokens: list[str], values: list[float], window: int = 5) -> dict[str, float]:
    """Оценка по аспектам: у каждого упоминания берём тональность рядом стоящих слов.

    Так «доставка опоздала» уходит в минус, хотя само слово «доставка»
    оценочным не является.
    """
    collected: dict[str, list[float]] = {}
    for index, token in enumerate(tokens):
        for aspect, stems in ASPECTS.items():
            if not any(token.startswith(stem) for stem in stems):
                continue
            start = max(0, index - window)
            local = sum(values[start:index + window + 1])
            if local or values[index]:
                collected.setdefault(aspect, []).append(local)
            else:
                collected.setdefault(aspect, []).append(0.0)
    squashed = {
        aspect: [value / (abs(value) + 3.0) for value in scores]
        for aspect, scores in collected.items()
    }
    return {
        aspect: round(sum(scores) / len(scores), 3)
        for aspect, scores in squashed.items()
    }


def _clause_weights(tokens: list[str]) -> list[float]:
    """Части предложения после «но»/«однако» весят больше."""
    weights = [1.0] * len(tokens)
    multiplier = 1.0
    for index, token in enumerate(tokens):
        if token in ("но", "однако", "хотя", "зато"):
            multiplier = 1.5
        elif token in ("и", "также"):
            pass
        weights[index] = multiplier
    return weights


def label_ru(label: str) -> str:
    return {"positive": "Позитив", "negative": "Негатив"}.get(label, "Нейтрально")
